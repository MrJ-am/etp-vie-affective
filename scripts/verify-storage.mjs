import {execFileSync} from "node:child_process";
import assert from "node:assert/strict";
import {scryptSync} from "node:crypto";
const compose=["compose","-p","mon-carnet-tests","-f","compose.test.yaml"];
const docker=(args,input)=>execFileSync("docker",[...compose,...args],{input,encoding:"utf8",stdio:["pipe","pipe","pipe"]});
const sql="SELECT EXISTS(SELECT 1 FROM coffres WHERE payload::text LIKE '%SENTINEL_%') OR EXISTS(SELECT 1 FROM objets WHERE payload::text LIKE '%SENTINEL_%') OR EXISTS(SELECT 1 FROM archives WHERE payload::text LIKE '%SENTINEL_%');";
assert.equal(docker(["exec","-T","database","psql","-U","carnet_test","-d","carnet_test","-At"],sql).trim(),"f");
assert.ok(!docker(["logs","--no-color","backend"]).includes("SENTINEL_FICTIVE_CARNET_7482"));
const stored=docker(["exec","-T","database","psql","-U","carnet_test","-d","carnet_test","-At"],"SELECT password_hash FROM comptes WHERE pseudonyme LIKE 'pwa_%' LIMIT 1;").trim();
assert.match(stored,/^scrypt-v1\$[0-9a-f]{32}\$[0-9a-f]{64}$/);
const [,salt,actual]=stored.split("$");
const expected=scryptSync("Mot_de_passe_fictif_2026",Buffer.from(salt,"hex"),32,{N:32768,r:8,p:3,maxmem:64*1024*1024}).toString("hex");
assert.equal(actual,expected);
console.log("Base : aucune sentinelle en clair dans coffres, objets et archives.");
console.log("Logs Rust : aucune sentinelle en clair.");
console.log("scrypt Rust : hash du compte fictif identique au calcul Node/OpenSSL indépendant.");
